export function translateMessage(locale: SupportedLocale, key: string, params?: TranslateParams) {
  const template = messages[locale][key] ?? messages["en-US"][key] ?? messages[DEFAULT_LOCALE][key] ?? key;
  if (!params) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (_, paramKey: string) => String(params[paramKey] ?? ""));
}
